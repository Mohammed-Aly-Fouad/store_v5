-- تحديث updated_at تلقائيًا
CREATE OR REPLACE FUNCTION public.update_modified_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- دالة تطبيع النص (أ إ آ -> ا | ى -> ي | ة -> ه + إزالة التشكيل والتطويل)
CREATE OR REPLACE FUNCTION public.normalize_text(txt text)
RETURNS text AS $$
    SELECT btrim(
        regexp_replace(
            regexp_replace(
                translate(lower(txt), 'أإآىة', 'اااية'),
                '[\u064B-\u0652\u0640]', '', 'g'
            ),
            '\s+', ' ', 'g'
        )
    );
$$ LANGUAGE sql IMMUTABLE PARALLEL SAFE;

-- دالة الحد الأقصى لعمق التصنيفات (3 مستويات) ومنع الأب من أن يكون ابناً لنفسه
CREATE OR REPLACE FUNCTION public.check_category_depth()
RETURNS TRIGGER AS $$
DECLARE
    current_depth INT := 1;
    parent_cursor BIGINT := NEW.parent_id;
BEGIN
    -- منع التصنيف من أن يكون أبًا لنفسه
    IF NEW.id IS NOT NULL AND NEW.id = NEW.parent_id THEN
        RAISE EXCEPTION 'Category cannot be its own parent.';
    END IF;

    -- الصعود في شجرة الآباء
    WHILE parent_cursor IS NOT NULL LOOP
        current_depth := current_depth + 1;

        IF current_depth > 3 THEN
            RAISE EXCEPTION 'Category depth limit exceeded (Maximum 3 levels allowed).';
        END IF;

        SELECT parent_id INTO parent_cursor
        FROM public.categories
        WHERE id = parent_cursor;
    END LOOP;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- دالة ذكية لمنع تكرار الاسم بين حقلين (العربي والإنجليزي) حتى لو تم عكسهم بالخطأ داخل نفس الأب
CREATE OR REPLACE FUNCTION public.check_category_cross_field_uniqueness()
RETURNS TRIGGER AS $$
BEGIN
    -- 1. التأكد أن الاسم الإنجليزي الجديد غير موجود مسبقاً (لا في الإنجليزي ولا العربي) لنفس الأب
    IF EXISTS (
        SELECT 1 FROM public.categories 
        WHERE (id IS DISTINCT FROM NEW.id)
          AND (parent_id IS NOT DISTINCT FROM NEW.parent_id)
          AND (
              normalize_text(name_en) = normalize_text(NEW.name_en) 
              OR normalize_text(name_ar) = normalize_text(NEW.name_en)
          )
    ) THEN
        RAISE EXCEPTION 'هذا الاسم موجود بالفعل (سواء في خانة الإنجليزي أو العربي) داخل نفس التصنيف الأب.';
    END IF;

    -- 2. التأكد أن الاسم العربي الجديد غير موجود مسبقاً (لا في الإنجليزي ولا العربي) لنفس الأب
    IF EXISTS (
        SELECT 1 FROM public.categories 
        WHERE (id IS DISTINCT FROM NEW.id)
          AND (parent_id IS NOT DISTINCT FROM NEW.parent_id)
          AND (
              normalize_text(name_en) = normalize_text(NEW.name_ar) 
              OR normalize_text(name_ar) = normalize_text(NEW.name_ar)
          )
    ) THEN
        RAISE EXCEPTION 'هذا الاسم موجود بالفعل (سواء في خانة الإنجليزي أو العربي) داخل نفس التصنيف الأب.';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- دالة مزامنة التسلسل (Sequence) لتفادي أخطاء الـ IDs اليدوية
CREATE OR REPLACE FUNCTION public.sync_categories_sequence()
RETURNS TRIGGER AS $$
BEGIN
    PERFORM setval(
        pg_get_serial_sequence('public.categories', 'id'), 
        (SELECT GREATEST(MAX(id), 1) FROM public.categories)
    );
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ========================================================
-- 2. Table: public.categories
-- ========================================================

DROP TABLE IF EXISTS public.categories CASCADE;

CREATE TABLE public.categories
(
    id          BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    parent_id   BIGINT,
    name_en     character varying(255) NOT NULL,
    name_ar     character varying(255) NOT NULL,
    created_at  timestamp with time zone NOT NULL DEFAULT now(),
    updated_at  timestamp with time zone NOT NULL DEFAULT now(),

    CONSTRAINT categories_pkey PRIMARY KEY (id),
    CONSTRAINT fk_categories_parent FOREIGN KEY (parent_id)
        REFERENCES public.categories (id) MATCH SIMPLE
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    -- منع الأسماء الفارغة أو المسافات فقط
    CONSTRAINT categories_name_en_not_blank CHECK (btrim(name_en) <> ''),
    CONSTRAINT categories_name_ar_not_blank CHECK (btrim(name_ar) <> '')
);

