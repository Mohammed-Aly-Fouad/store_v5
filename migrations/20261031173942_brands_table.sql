-- 1. Table: public.brands
-- ========================================================

DROP TABLE IF EXISTS public.brands CASCADE;

CREATE TABLE public.brands
(
    id          BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name_en     character varying(255) NOT NULL,
    name_ar     character varying(255) NOT NULL,
    created_at  timestamp with time zone NOT NULL DEFAULT now(),
    updated_at  timestamp with time zone NOT NULL DEFAULT now(),

    CONSTRAINT brands_pkey PRIMARY KEY (id),

    -- منع الأسماء الفارغة أو المسافات فقط
    CONSTRAINT brands_name_en_not_blank CHECK (btrim(name_en) <> ''),
    CONSTRAINT brands_name_ar_not_blank CHECK (btrim(name_ar) <> '')
);

ALTER TABLE IF EXISTS public.brands OWNER TO mohammed;

-- ========================================================
-- 2. Indexes for brands (Handles Case, Arabic Normalization & ON CONFLICT)
-- ========================================================

-- فهارس فريدة مطلوبة لكي تعمل جملة ON CONFLICT بسلاسة أثناء الـ Seeding
CREATE UNIQUE INDEX idx_brands_unique_name_en
    ON public.brands (normalize_text(name_en));

CREATE UNIQUE INDEX idx_brands_unique_name_ar
    ON public.brands (normalize_text(name_ar));

-- تسريع البحث بـ LIKE 'xxx%' للغتين
CREATE INDEX idx_brands_search_name_ar
    ON public.brands (normalize_text(name_ar) text_pattern_ops);

CREATE INDEX idx_brands_search_name_en
    ON public.brands (normalize_text(name_en) text_pattern_ops);

-- ========================================================
-- 3. Triggers for brands
-- ========================================================

-- Trigger 1: تحديث تاريخ التعديل تلقائياً
DROP TRIGGER IF EXISTS update_brands_modtime ON public.brands;
CREATE TRIGGER update_brands_modtime
    BEFORE UPDATE ON public.brands
    FOR EACH ROW
    EXECUTE FUNCTION public.update_modified_column();

-- Trigger 2: منع التكرار وتبديل الحقول بالخطأ بين العربي والإنجليزي
DROP TRIGGER IF EXISTS enforce_brand_cross_field_uniqueness ON public.brands;
CREATE TRIGGER enforce_brand_cross_field_uniqueness
    BEFORE INSERT OR UPDATE ON public.brands
    FOR EACH ROW
    EXECUTE FUNCTION public.check_brand_cross_field_uniqueness();

-- Trigger 3: مزامنة عداد التسلسل تلقائياً بعد كل عملية إدخال (يدوي أو تلقائي)
DROP TRIGGER IF EXISTS trg_sync_brands_sequence ON public.brands;
CREATE TRIGGER trg_sync_brands_sequence
    AFTER INSERT ON public.brands
    FOR EACH ROW
    EXECUTE FUNCTION public.sync_brands_sequence();