-- تحديث updated_at تلقائيًا
CREATE OR REPLACE FUNCTION public.update_modified_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- دالة تطبيع الاسم العربي والإنجليزي:
--   أ إ آ ة ى -> ا ي ة   |   إزالة التشكيل والتطويل   |   تحويل إلى lowercase
CREATE OR REPLACE FUNCTION public.normalize_text(txt text)
RETURNS text AS $$
    SELECT btrim(
        regexp_replace(
            regexp_replace(
                translate(lower(txt), 'أإآىة', 'اااية'),
                '[\u064B-\u0652\u0640]', '', 'g'
            ),
            '\s+', ' ', 'g'
        )
    );
$$ LANGUAGE sql IMMUTABLE PARALLEL SAFE;

-- دالة مزامنة التسلسل (Sequence) لتفادي خطأ التداخل عند إدخال معرفات يدوياً
CREATE OR REPLACE FUNCTION public.sync_brands_sequence()
RETURNS TRIGGER AS $$
BEGIN
    PERFORM setval(
        pg_get_serial_sequence('public.brands', 'id'), 
        (SELECT GREATEST(MAX(id), 1) FROM public.brands)
    );
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- دالة لمنع تكرار الاسم بين حقلين (العربي والإنجليزي) حتى لو تم عكسهم بالخطأ في جدول الماركات
CREATE OR REPLACE FUNCTION public.check_brand_cross_field_uniqueness()
RETURNS TRIGGER AS $$
BEGIN
    -- 1. التأكد أن الاسم الإنجليزي الجديد غير موجود مسبقاً (لا في الإنجليزي ولا العربي)
    IF EXISTS (
        SELECT 1 FROM public.brands 
        WHERE (id IS DISTINCT FROM NEW.id)
          AND (
              normalize_text(name_en) = normalize_text(NEW.name_en) 
              OR normalize_text(name_ar) = normalize_text(NEW.name_en)
          )
    ) THEN
        RAISE EXCEPTION 'هذا الاسم مسجل مسبقاً (سواء في خانة الإنجليزي أو العربي) لماركة أخرى.';
    END IF;

    -- 2. التأكد أن الاسم العربي الجديد غير موجود مسبقاً (لا في الإنجليزي ولا العربي)
    IF EXISTS (
        SELECT 1 FROM public.brands 
        WHERE (id IS DISTINCT FROM NEW.id)
          AND (
              normalize_text(name_en) = normalize_text(NEW.name_ar) 
              OR normalize_text(name_ar) = normalize_text(NEW.name_ar)
          )
    ) THEN
        RAISE EXCEPTION 'هذا الاسم مسجل مسبقاً (سواء في خانة الإنجليزي أو العربي) لماركة أخرى.';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

